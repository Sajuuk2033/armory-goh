"""Generated soldier breeds: what lets supply crates refill edited soldiers (a crate refills a soldier to his BREED inventory).

Why: a Conquest save stores each soldier's *current* pack ({Inventory}), but the soldier's *breed* (a `set/breed/.../*.set`
file) lists what that kind of soldier is SUPPOSED to carry. Players report that crates only top up soldiers whose weapons
still match their breed, so the engine seems to refill against the breed's list. For every edited loadout we therefore
generate a copy of the soldier's own breed whose `{inventory}` matches the new pack, ship all of them in a tiny local mod
(`<game>/mods/armory_breeds`) and point the edited soldiers at them.

Data only: one .set text per loadout inside a zip .pak, plus a mod.info. No DLL/EXE/script, so nothing here is
Workshop-hostile; Armory just writes it into the user's own game folder.
"""
from __future__ import annotations

import hashlib
import io
import re
import zipfile
from pathlib import Path

from catalog import block, child

MOD_ID = "armory_breeds"
MOD_INFO = """{mod
\t{name "Armory soldier breeds"}
\t{desc "Auto-generated by Armory: one soldier breed per custom loadout so supply crates refill edited soldiers. Safe to leave enabled."}
\t{minGameVersion "1.067"}
\t{maxGameVersion "9.999"}
}
"""


def find_base(game: Path, workshop: Path | None, breed: str) -> str | None:
    """Text of set/breed/<breed>.set, preferring mods over the base game (the same order the game applies)."""
    name = f"set/breed/{breed}.set"
    paks = [game / "resource" / "gamelogic.pak"]
    for root in [game / "mods"] + ([workshop] if workshop else []):
        if root.is_dir():
            paks += sorted(root.rglob("*.pak"))
    text = None
    for p in paks:
        try:
            with zipfile.ZipFile(p) as z:
                if name in z.namelist():
                    text = z.read(name).decode("utf-8", "replace")
        except Exception:
            continue
    return text


def find_bases(game: Path, workshop: Path | None, breeds: set) -> dict:
    """{breed: text} for many breeds in ONE pass over the paks (find_base opens every pak each call; with a big
    Workshop folder that is far too slow to do per soldier)."""
    want = {f"set/breed/{b}.set": b for b in breeds}
    paks = [game / "resource" / "gamelogic.pak"]
    for root in [game / "mods"] + ([workshop] if workshop else []):
        if root.is_dir():
            paks += sorted(root.rglob("*.pak"))
    out = {}
    for p in paks:
        try:
            with zipfile.ZipFile(p) as z:
                for n in want.keys() & set(z.namelist()):
                    out[want[n]] = z.read(n).decode("utf-8", "replace")
        except Exception:
            continue
    return out


def inventory_lines(loadout: dict, cat=None) -> list[str]:
    """Breed-syntax lines for a loadout: weapons, ammo as 'total stack', then everything else as bare repeated items.

    The breed is the soldier's *intended full kit* (what crates refill him to), not a snapshot of a half-spent pack: if the
    pack being saved carries less ammo for a weapon than that weapon normally gets, the breed uses the normal amount
    (`cat` = the loaded catalog; without it the pack is used as-is)."""
    weapons, ammo, other = [], {}, []
    for e in loadout["entries"]:
        name = " ".join(e["tokens"])
        if e["role"] == "ammo":
            n = int(float(e["mid"][0])) if e["mid"] else 0
            a = ammo.setdefault(name, {"total": 0, "stack": 0})
            a["total"] += n
            a["stack"] = max(a["stack"], n)
        elif e["role"] in ("primary", "sidearm", "launcher") or "filled" in e["mid"]:
            # {in_hands 0} puts the FIRST weapon in his hands (vanilla AT soldiers list the SMG first, launcher after)
            rank = 0 if e.get("user") == "hand_right" else 2 if e["role"] == "launcher" else 1
            weapons.append((rank, '{item "%s" filled}' % name))
            stem = cat.weapon_ammo(e["key"]) if cat and e.get("key") else None
            if stem:
                aname = stem.replace(".", " ") + " ammo"
                full = cat.total(stem) or 0
                a = ammo.setdefault(aname, {"total": 0, "stack": 0})
                a["stack"] = max(a["stack"], cat.stack(stem))
                a["total"] = max(a["total"], full)
        else:
            other.append('{item "%s"}' % name)
    lines = [w for _, w in sorted(weapons, key=lambda w: w[0])] + ['{item "%s" %d %d}' % (n, a["total"], a["stack"]) for n, a in sorted(ammo.items()) if a["total"]]
    return lines + other


def make_breed(base_text: str, lines: list[str] | None, skin: str | None = None, vet: int | None = None,
               perks: dict | None = None, icon: str | None = None, tag: str | None = None, portrait: str | None = None) -> str:
    """The base breed with its {inventory} swapped (lines=None keeps it), optionally a new {skin}, veterancy level and
    skill layers (`perks` = a perks.py spec; only the layers it names change). Armour and everything else stay the soldier's own."""
    text = base_text
    if perks:
        import perks as _perks
        text = _perks.apply(text, perks)
    if icon is not None or tag is not None or portrait is not None:
        import identity
        text = identity.apply(text, icon, tag, portrait)
    if lines is not None:
        start = text.find("{inventory")
        if start < 0:
            raise ValueError("base breed has no {inventory} block")
        old = block(text, start)
        new = "{inventory\n" + "".join("\t\t%s\n" % l for l in lines) + "\n\t\t{in_hands 0}\n\t}"
        text = text[:start] + new + text[start + len(old):]
    if skin:
        text, k = re.subn(r'\{skin "[^"]*"\}', lambda m: '{skin "%s"}' % skin, text, count=1)
        if not k:
            raise ValueError("base breed has no {skin}")
    if vet is not None:
        text, k = re.subn(r'\("veterancy_lvl_\d+"\)', '("veterancy_lvl_%d")' % int(vet), text, count=1)
        if not k:
            raise ValueError("base breed has no veterancy level to change")
    return text


def breed_path(base_breed: str, base_text: str, lines: list[str]) -> str:
    h = hashlib.sha1((base_text + "\n".join(lines)).encode("utf-8")).hexdigest()[:10]
    d = base_breed.rsplit("/", 1)[0] if "/" in base_breed else ""
    return (d + "/" if d else "") + "arm_" + h


def needs_breed(game: Path, workshop: Path | None, loadout: dict, breed: str, texts: dict | None = None) -> bool:
    """True for a soldier whose weapons no longer match his breed (edited in an earlier save, before breeds existed) or who
    already sits on an Armory breed (so older, ammo-less ones get regenerated). Unedited soldiers return False.
    `texts` = find_bases() result, so a whole save is checked with one pass over the paks."""
    if breed.rsplit("/", 1)[-1].startswith("arm_"):
        return True
    text = texts.get(breed) if texts is not None else find_base(game, workshop, breed)
    if text is None:
        return False
    inv = text[text.find("{inventory"):]
    want = set(re.findall(r'\{item "([^"]+)" filled', inv))
    have = {" ".join(e["tokens"]) for e in loadout["entries"] if e["role"] in ("primary", "sidearm") and "filled" in e["mid"]}
    return want != have


class Files(dict):
    """{new breed path: set text}, plus `.labels` {new breed path: the breed it was made from} so install() can name it."""
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self.labels = {}


def pretty_breed(path: str) -> str:
    return path.rsplit("/", 1)[-1].replace("_", " ").strip().capitalize() or "Soldier"


LOC_FILE = "default/interface/text/desc/armory_breeds.pot"
LOC_HEAD = "\n".join(['msgid ""', 'msgstr ""', r'"Project-Id-Version: Armory soldier breeds\n"', r'"Language: en\n"', r'"MIME-Version: 1.0\n"',
                      r'"Content-Type: text/plain; charset=UTF-8\n"', r'"Content-Transfer-Encoding: 8bit\n"']) + "\n\n"
LOC_ENTRY = re.compile(r'msgctxt "desc/human/([^"]+)"\s*\nmsgid "((?:[^"\\]|\\.)*)"')


def read_loc(pak: Path) -> dict:
    """{breed path: on-screen name} already written by earlier runs."""
    if not pak.is_file():
        return {}
    with zipfile.ZipFile(pak) as z:
        if LOC_FILE not in z.namelist():
            return {}
        t = z.read(LOC_FILE).decode("utf-8", "replace")
    return {a: b.replace('\\"', '"') for a, b in LOC_ENTRY.findall(t)}


def write_loc(root: Path, labels: dict, breed_paths, names: dict | None) -> None:
    """The game labels a soldier type with the localized text `desc/human/<breed path>`; without an entry it shows the raw key
    (e.g. desc/human/mp/ger/mid/arm_dbf3822385). Give every Armory breed the name of the breed it was made from."""
    pak = root / "localizations" / "default.pak"
    cur = read_loc(pak)
    for newp, base in labels.items():
        if base.rsplit("/", 1)[-1].startswith("arm_"):
            cur[newp] = cur.get(base) or "Soldier"                  # regenerated from an Armory breed: keep ITS name
        else:
            cur[newp] = (names or {}).get(base) or pretty_breed(base)
    for p in breed_paths:                                           # breeds made before names existed
        cur.setdefault(p, "Soldier")
    body = "".join('msgctxt "desc/human/%s"\nmsgid "%s"\nmsgstr ""\n\n' % (k, v.replace('"', '\\"')) for k, v in sorted(cur.items()))
    pak.parent.mkdir(parents=True, exist_ok=True)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(LOC_FILE, (LOC_HEAD + body).encode("utf-8"))
    pak.write_bytes(buf.getvalue())


def plan(game: Path, workshop: Path | None, edits: dict, breeds: dict, cat=None, looks: dict | None = None,
         texts: dict | None = None):
    """edits {eid: loadout}, breeds {eid: current breed path}. Returns ({eid: new breed path}, {new path: set text}).
    Raises ValueError (with the soldier's breed named) if a base breed can't be found."""
    remap, files = {}, Files()
    looks = looks or {}
    order = list(edits) + [e for e in looks if e not in edits]
    if texts is None:
        texts = find_bases(game, workshop, {breeds[e] for e in order if breeds.get(e)})
    for eid in order:
        lo = edits.get(eid)                       # None = skin / rank change only: keep the breed's own inventory
        base = breeds.get(eid)
        if not base:
            continue
        text = texts.get(base)                    # (an Armory breed is regenerated from ITS own text, same lookup)
        if text is None:
            raise ValueError(f"Can't find the breed file for {base}")
        lines = inventory_lines(lo, cat) if lo is not None else None
        look = looks.get(eid) or {}
        body = make_breed(text, lines, look.get("skin"), look.get("vet"), look.get("perks"), look.get("icon"), look.get("tag"), look.get("portrait"))
        newp = breed_path(base, body, [])
        remap[eid] = newp
        files[newp] = body
        files.labels[newp] = base                 # install() gives the new breed the same on-screen name as the one it came from
    return remap, files


def install(game: Path, files: dict, mods_dir: Path | None = None, names: dict | None = None) -> Path:
    """Add the breeds to <game>/mods/armory_breeds (kept across runs: older saves still point at older breeds) and give each
    an on-screen name. `names` = the catalog's {breed path: game name}; read from the game's own text when not given."""
    root = (mods_dir or game / "mods") / MOD_ID
    (root / "resource").mkdir(parents=True, exist_ok=True)
    pak = root / "resource" / "gamelogic.pak"
    cur = {}
    if pak.is_file():
        with zipfile.ZipFile(pak) as z:
            cur = {n: z.read(n) for n in z.namelist()}
    for path, text in files.items():
        cur[f"set/breed/{path}.set"] = text.replace("\r", "").encode("utf-8")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for n in sorted(cur):
            z.writestr(n, cur[n])
    pak.write_bytes(buf.getvalue())
    labels = getattr(files, "labels", {})
    if names is None and any(not b.rsplit("/", 1)[-1].startswith("arm_") for b in labels.values()):
        import catalog
        names = catalog.read_localization(game)["breeds"]
    write_loc(root, labels, [n[len("set/breed/"):-len(".set")] for n in cur if n.startswith("set/breed/") and n.endswith(".set")], names)
    (root / "mod.info").write_text(MOD_INFO, encoding="utf-8")
    return root


def add_to_mods(status: str) -> str:
    """Append "armory_breeds:0" to the save's {mods ...} list (creating it if the save had none). Idempotent."""
    crlf = "\r\n" in status
    s = status.replace("\r", "")
    if f'"{MOD_ID}:0"' in s:
        return status
    m = re.search(r"\{mods([^}]*)\}", s)
    if m:
        body = m.group(1).rstrip()
        s = s[:m.start()] + "{mods" + body + f'\n\t\t"{MOD_ID}:0"\n\t' + "}" + s[m.end():]
    else:
        t = re.search(r"\{timestamp [^}\n]*\}\n", s)              # the game puts {mods} right after the timestamp
        if not t:
            raise ValueError("Could not find where to list the mod in the save info")
        s = s[:t.end()] + f'\t{{mods\n\t\t"{MOD_ID}:0"\n\t}}\n' + s[t.end():]
    return s.replace("\n", "\r\n") if crlf else s
